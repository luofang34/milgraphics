//! Port of mil-sym-java RenderMultipoints/clsRenderer.getCMLineType: the line type of a
//! symbol set 25 (control measures) entity code, by symbol version.

use crate::engine::tactical_lines::*;

/// Upstream `SymbolID.Version_2525E`.
pub(crate) const VERSION_2525E: u8 = 13;
/// Upstream `SymbolID.Version_2525Ech1`.
pub(crate) const VERSION_2525E_CH1: u8 = 15;

/// The line type of control-measure `entity`, or `None` where upstream returns -1.
/// Entities whose drawing changed between editions resolve per edition first.
pub(crate) fn cm_line_type(version: u8, entity: u32) -> Option<i32> {
    if version >= VERSION_2525E_CH1 {
        match entity {
            172000 => return Some(WFZ),
            240804 => return None,
            _ => {}
        }
    }
    if version >= VERSION_2525E {
        match entity {
            120500 => return Some(BASE_CAMP),
            120600 => return Some(GUERILLA_BASE),
            260400 => return Some(BCL),
            310100 => return Some(DHA),
            172000 => return Some(WFZ_REVD),
            _ => {}
        }
    } else {
        match entity {
            120500 => return Some(BASE_CAMP_REVD),
            120600 => return Some(GUERILLA_BASE_REVD),
            260400 => return Some(BCL_REVD),
            310100 => return Some(DHA_REVD),
            150300 => return Some(ASSY),
            241601 => return Some(SENSOR),
            241602 => return Some(SENSOR_RECTANGULAR),
            241603 => return Some(SENSOR_CIRCULAR),
            172000 => return Some(WFZ_REVD),
            _ => {}
        }
    }
    cm_line_type_any_version(entity)
}

/// Entities whose line type does not depend on the edition.
fn cm_line_type_any_version(entity: u32) -> Option<i32> {
    let parts: [fn(u32) -> Option<i32>; 5] =
        [cm_part_0, cm_part_1, cm_part_2, cm_part_3, cm_part_4];
    parts.iter().find_map(|part| part(entity))
}

